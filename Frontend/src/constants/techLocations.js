// Helper to look up country data
export function getCountryData(countryId = "India") {
  const match = TECH_COUNTRIES.find(
    (c) => c.id.toLowerCase() === countryId.toLowerCase() || c.name.toLowerCase() === countryId.toLowerCase()
  );
  return match || TECH_COUNTRIES[0];
}

// Helper to match if a job location string belongs to a specific country
export function matchesCountry(jobLocation = "", countryId = "All") {
  if (!countryId || countryId === "All" || countryId.toLowerCase() === "all") return true;

  const loc = (jobLocation || "").toLowerCase();
  const cLower = countryId.toLowerCase();

  if (cLower === "remote") {
    return loc.includes("remote") || loc.includes("wfh") || loc.includes("anywhere") || loc.includes("virtual");
  }

  const country = TECH_COUNTRIES.find((c) => c.id.toLowerCase() === cLower || c.name.toLowerCase() === cLower);
  if (!country) return loc.includes(cLower);

  // Check country name, code, and keywords from all its tech hubs
  if (loc.includes(country.name.toLowerCase()) || loc.includes(country.code.toLowerCase())) {
    return true;
  }

  for (const hub of country.techHubs) {
    if (hub.keywords.some((kw) => loc.includes(kw))) {
      return true;
    }
  }

  return false;
}

// Helper to match if a job location string belongs to a specific tech hub
export function matchesTechHub(jobLocation = "", techHubId = "All", countryId = "India") {
  if (!techHubId || techHubId === "All" || techHubId.toLowerCase() === "all") {
    return matchesCountry(jobLocation, countryId);
  }

  const loc = (jobLocation || "").toLowerCase();
  const techLower = techHubId.toLowerCase();

  // First search in selected country
  const country = getCountryData(countryId);
  let hub = country?.techHubs?.find(
    (h) => h.id.toLowerCase() === techLower || h.name.toLowerCase() === techLower
  );

  // If not found in selected country, search across all countries
  if (!hub) {
    for (const c of TECH_COUNTRIES) {
      const found = c.techHubs?.find(
        (h) => h.id.toLowerCase() === techLower || h.name.toLowerCase() === techLower
      );
      if (found) {
        hub = found;
        break;
      }
    }
  }

  if (!hub) {
    return loc.includes(techLower);
  }

  return hub.keywords.some((kw) => loc.includes(kw));
}
